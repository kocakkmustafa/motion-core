/// Fourteen-locale account copy. Existing hosts may keep their locale resolver;
/// [of] also works without this delegate and reads the inherited host locale.
class MotionAccountLocalizations {
  MotionAccountLocalizations(Locale? locale) : locale = localeFor(locale);

  final Locale locale;

  static const supportedLocales = <Locale>[
    Locale('tr'),
    Locale('en'),
    Locale('es', '419'),
    Locale('pt', 'BR'),
    Locale('de'),
    Locale('fr'),
    Locale('ja'),
    Locale('ar'),
    Locale('it'),
    Locale('ko'),
    Locale('id'),
    Locale('pl'),
    Locale('hi'),
    Locale.fromSubtags(languageCode: 'zh', scriptCode: 'Hans'),
  ];

  static const LocalizationsDelegate<MotionAccountLocalizations> delegate =
      _MotionAccountLocalizationsDelegate();

  static const delegates = <LocalizationsDelegate<dynamic>>[
    delegate,
    GlobalMaterialLocalizations.delegate,
    GlobalWidgetsLocalizations.delegate,
    GlobalCupertinoLocalizations.delegate,
  ];

  /// All Spanish/Portuguese variants select the approved Latin American/Brazil
  /// copy. Unknown languages deliberately fall back to English.
  static Locale localeFor(Locale? requested) =>
      switch (requested?.languageCode) {
        'tr' => const Locale('tr'),
        'es' => const Locale('es', '419'),
        'pt' => const Locale('pt', 'BR'),
        'de' => const Locale('de'),
        'fr' => const Locale('fr'),
        'ja' => const Locale('ja'),
        'ar' => const Locale('ar'),
        'it' => const Locale('it'),
        'ko' => const Locale('ko'),
        'id' => const Locale('id'),
        'pl' => const Locale('pl'),
        'hi' => const Locale('hi'),
        'zh' when _supportsChinese(requested!) => const Locale.fromSubtags(
          languageCode: 'zh',
          scriptCode: 'Hans',
        ),
        _ => const Locale('en'),
      };

  static bool _supportsChinese(Locale locale) =>
      locale.scriptCode == 'Hans' ||
      (locale.scriptCode == null &&
          !const {'TW', 'HK', 'MO'}.contains(locale.countryCode));

  static bool _supportsRequested(Locale locale) =>
      (locale.languageCode != 'zh' || _supportsChinese(locale)) &&
      supportedLocales.any((item) => item.languageCode == locale.languageCode);

  /// Resolve ordered device/host preferences, skipping unsupported languages.
  /// Explicit parent Localizations or the gate's locale takes precedence.
  static Locale localeListResolutionCallback(
    List<Locale>? requested,
    Iterable<Locale> supported,
  ) {
    for (final locale in requested ?? const <Locale>[]) {
      if (!_supportsRequested(locale)) continue;
      final target = localeFor(locale);
      for (final candidate in supported) {
        if (candidate == target) return candidate;
      }
      for (final candidate in supported) {
        if (candidate.languageCode == target.languageCode &&
            _supportsRequested(candidate)) {
          return candidate;
        }
      }
    }
    return localeResolutionCallback(null, supported);
  }

  /// Optional MaterialApp callback. It never returns a locale the host omitted.
  static Locale localeResolutionCallback(
    Locale? requested,
    Iterable<Locale> supported,
  ) {
    final target = localeFor(requested);
    for (final candidate in supported) {
      if (candidate == target) return candidate;
    }
    for (final candidate in supported) {
      if (candidate.languageCode == target.languageCode &&
          _supportsRequested(candidate))
        return candidate;
    }
    for (final candidate in supported) {
      if (candidate.languageCode == 'en') return candidate;
    }
    return supported.isEmpty ? const Locale('en') : supported.first;
  }

  static MotionAccountLocalizations of(BuildContext context) =>
      Localizations.of<MotionAccountLocalizations>(
        context,
        MotionAccountLocalizations,
      ) ??
      MotionAccountLocalizations(Localizations.maybeLocaleOf(context));

  TextDirection get textDirection =>
      locale.languageCode == 'ar' ? TextDirection.rtl : TextDirection.ltr;

  /// Exposes the untranslated template for catalog/placeholder completeness
  /// checks. Rendering parameterized messages uses typed methods below.
  static String templateFor(Locale locale, MotionAccountString key) =>
      _messages[key]!.forLocale(localeFor(locale));

  String text(MotionAccountString key) {
    final template = templateFor(locale, key);
    if (_placeholder.hasMatch(template)) {
      throw ArgumentError.value(key, 'key', 'Use the typed placeholder method');
    }
    return template;
  }

  String membershipForApp(String appName) =>
      _format(MotionAccountString.appMembership, {'appName': appName});

  /// "{days} days free, then {price} per month/year". [price] is the store's
  /// localized recurring price; nothing is hard-coded.
  String trialThenPrice({
    required bool yearly,
    required int days,
    required String price,
  }) => _format(
    yearly
        ? MotionAccountString.trialThenYearly
        : MotionAccountString.trialThenMonthly,
    {'days': '$days', 'price': price},
  );

  static final _placeholder = RegExp(r'\{([A-Za-z][A-Za-z0-9]*)\}');

  String _format(MotionAccountString key, Map<String, String> values) {
    final template = templateFor(locale, key);
    final expected = _placeholder
        .allMatches(template)
        .map((match) => match.group(1)!)
        .toSet();
    if (expected.length != values.length ||
        !expected.every(values.containsKey)) {
      throw ArgumentError('Placeholder names do not match $key');
    }
    // A value is inserted once; braces in user-supplied names are not expanded.
    return template.replaceAllMapped(
      _placeholder,
      (match) => values[match.group(1)!]!,
    );
  }
}

class _MotionAccountLocalizationsDelegate
    extends LocalizationsDelegate<MotionAccountLocalizations> {
  const _MotionAccountLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) =>
      MotionAccountLocalizations._supportsRequested(locale);

  @override
  Future<MotionAccountLocalizations> load(Locale locale) =>
      SynchronousFuture(MotionAccountLocalizations(locale));

  @override
  bool shouldReload(_MotionAccountLocalizationsDelegate old) => false;
}

